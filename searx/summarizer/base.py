"""Base classes and configuration for the result *summarizer*.

The summarizer produces an optional, privacy-first summary of the search
results (see the ``search.summarizer`` settings).  Implementations live in
:py:mod:`searx.summarizer.backends`.
"""

__all__ = ["SummarizerConfig", "Summarizer"]

import abc
import dataclasses
import typing as t

if t.TYPE_CHECKING:
    from searx.result_types import MainResult, LegacyResult

log_name = "searx.summarizer"


@dataclasses.dataclass
class SummarizerConfig:
    """Configuration of the :py:obj:`Summarizer`.

    Instances are built from the ``search.summarizer`` section of the settings,
    see :py:func:`searx.summarizer.build_config`.
    """

    enabled: bool = False
    """If unset, no summary is generated (default: disabled)."""

    backend: str = "offline"
    """Name of the backend to use (see :py:data:`searx.summarizer.backends.BACKENDS`)."""

    model: str = "llama3"
    """Model name passed to the local backend."""

    base_url: str = "http://127.0.0.1:11434"
    """Base URL of the local inference service (Ollama by default)."""

    timeout: float = 5.0
    """Strict timeout (seconds) for a single summarization request."""

    local_only: bool = True
    """Only allow loopback hosts.  Rejects non-local ``base_url`` values."""

    max_tokens: int = 256
    """Maximum number of tokens generated by the backend."""

    temperature: float = 0.2
    """Sampling temperature."""

    min_results: int = 3
    """Minimum number of results required to trigger a summary."""

    categories: list[str] = dataclasses.field(default_factory=lambda: ["general"])
    """Categories for which a summary is generated (empty = all)."""

    max_results: int = 8
    """Maximum number of results included in the prompt."""

    max_input_chars: int = 4000
    """Maximum number of characters of the generated prompt."""


def _result_field(result: "MainResult | LegacyResult", name: str, default: str = "") -> str:
    """Read a text field from a :py:obj:`MainResult` or a :py:obj:`LegacyResult`."""
    if isinstance(result, dict):
        value = result.get(name, default)
    else:
        value = getattr(result, name, default)
    return value if value is not None else default


class Summarizer(abc.ABC):
    """Abstract base class of all summarizer backends."""

    name: str = "base"
    """Name of the backend (must match the key in ``BACKENDS``)."""

    def __init__(self, config: SummarizerConfig) -> None:
        self.config: SummarizerConfig = config

    @abc.abstractmethod
    async def summarize(
        self, results: "list[MainResult | LegacyResult]", query: str, context: str | None = None
    ) -> str | None:
        """Generate a summary for ``results``.

        ``context`` is an optional block of relevant context (e.g. from the local
        semantic memory) that the backend may include in the prompt.

        :return: the summary text, or ``None`` if no summary could be produced.
        """
        raise NotImplementedError

    def build_prompt(
        self, results: "list[MainResult | LegacyResult]", query: str, context: str | None = None
    ) -> str:
        """Build the prompt from the results of the query.

        The prompt respects :py:obj:`SummarizerConfig.max_results` and
        :py:obj:`SummarizerConfig.max_input_chars`.  When ``context`` is given, it
        is included as an additional, clearly delimited context block.
        """
        parts: list[str] = [
            "Answer the question using only the sources below.",
            "Be concise, neutral and factual. Do not invent information.",
            "",
            f"Question: {query}",
            "",
        ]
        total = sum(len(p) for p in parts)

        if context:
            parts.append(context)
            parts.append("")
            total += len(context)

        parts.append("Sources:")

        count = 0
        for result in results:
            if count >= self.config.max_results:
                break
            title = _result_field(result, "title").strip()
            url = _result_field(result, "url").strip()
            content = _result_field(result, "content").strip()
            entry = f"- {title}\n  {url}\n  {content}".rstrip()
            if not entry.strip():
                continue
            remaining = self.config.max_input_chars - total
            if remaining <= 0:
                break
            if len(entry) > remaining:
                entry = entry[:remaining]
            parts.append(entry)
            total += len(entry)
            count += 1

        parts.append("")
        parts.append("Summary:")
        return "\n".join(parts)
